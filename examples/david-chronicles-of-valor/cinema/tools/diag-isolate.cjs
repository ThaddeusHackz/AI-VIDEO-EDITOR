const path=require('node:path');const { launch }=require('./harness.cjs');const ROOT=path.resolve(__dirname,'..');
let H=null;
(async()=>{
 H=await launch({root:ROOT});
 await H.page.goto(H.url('/tools/render.html?scale=0.25&quality=0.4'),{waitUntil:'load',timeout:180000});
 await H.page.waitForFunction('window.__status==="ready"',{timeout:900000,polling:500});
 const out=await H.page.evaluate(`(()=>{
  const film=window.__film,T=window.__three,gl=film.renderer.getContext(),r=film.renderer;
  const TW=480,TH=270;
  const rt=new T.WebGLRenderTarget(TW,TH,{type:T.UnsignedByteType});
  const buf=new Uint8Array(TW*TH*4);
  film.setFrame(6000);
  const all=[...film.actors.values()];
  const setVis=(v)=>{ for(const a of all) a.root.visible=!!v; };
  const measure=(label,setup)=>{
    setVis(false); film.sky.visible=false; film.terrain.visible=false; film.crowd.visible=false;
    film.rain.visible=false; film.fx.group.visible=false; film.ruin.visible=false; film.chariot.visible=false;
    film.rays.visible=false; film.title.visible=false;
    setup();
    r.setRenderTarget(rt);
    const t0=performance.now();
    r.clear();
    r.render(film.scene,film.camera);
    gl.readPixels(0,0,TW,TH,gl.RGBA,gl.UNSIGNED_BYTE,buf);
    const t=+(performance.now()-t0).toFixed(0);
    r.setRenderTarget(null);
    return t;
  };
  const res={};
  res.empty=measure('empty',()=>{});
  res.sky=measure('sky',()=>{film.sky.visible=true;});
  res.terrain=measure('terrain',()=>{film.terrain.visible=true;});
  res.actors1=measure('1 actor',()=>{all[0].root.visible=true;});
  res.actors15=measure('15 actors',()=>{setVis(true);});
  film.renderer.shadowMap.enabled=false;
  res.actors15_noShadow=measure('15 actors no shadow',()=>{setVis(true);});
  film.renderer.shadowMap.enabled=true;
  res.actors15_shadow_map1024=(()=>{ film.sun.shadow.mapSize.set(1024,1024); if(film.sun.shadow.map){film.sun.shadow.map.dispose(); film.sun.shadow.map=null;} return measure('15 actors shadow 1024',()=>{setVis(true);}); })();
  res.crowd=measure('crowd',()=>{film.crowd.visible=true;});
  res.rain=measure('rain',()=>{film.rain.visible=true;});
  res.fx=measure('fx',()=>{film.fx.group.visible=true;});
  res.ruin=measure('ruin',()=>{film.ruin.visible=true; film.chariot.visible=true;});
  res.everything=measure('everything',()=>{setVis(true);film.sky.visible=true;film.terrain.visible=true;film.crowd.visible=true;film.rain.visible=true;film.fx.group.visible=true;film.ruin.visible=true;film.chariot.visible=true;});
  res.drawCalls=r.info.render.calls;
  return res;
 })()`);
 console.log(JSON.stringify(out,null,1));
 await H.close();
})().catch(e=>{console.error('FAIL',e.message);if(H&&H.logs.length)console.error(H.logs.slice(0,20).join('\n'));process.exit(1);});
